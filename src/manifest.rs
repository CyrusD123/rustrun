//! Rendering the synthetic `Cargo.toml`.
//!
//! The key design decision of the project lives here: the `[[bin]]` target's
//! `path` is the *original* script, wherever it is on disk. The manifest,
//! `Cargo.lock` and `target/` all live in a hidden cache directory, but rustc
//! opens the real file, so `mod foo;`, `#[path = ...]`, `include!`,
//! `include_str!` and `include_bytes!` all resolve relative to the script's
//! real directory with no rewriting, copying or environment-variable tricks.

use std::path::Path;

use anyhow::{Context, Result};

use crate::resolve::ResolvedDep;

pub const DEFAULT_EDITION: &str = "2024";

pub struct ManifestInput<'a> {
    pub package_name: &'a str,
    pub bin_name: &'a str,
    /// Absolute, canonical path of the script.
    pub script_path: &'a Path,
    pub edition: &'a str,
    pub deps: &'a [ResolvedDep],
}

/// A TOML basic string, with all escaping handled by the `toml` crate.
fn quote(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

/// A TOML key, quoted only when necessary.
fn key(s: &str) -> String {
    if !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_') {
        s.to_string()
    } else {
        quote(s)
    }
}

pub fn render(input: &ManifestInput) -> Result<String> {
    let script = input
        .script_path
        .to_str()
        .with_context(|| format!("script path {} is not valid UTF-8", input.script_path.display()))?;

    let mut out = String::new();
    out.push_str(&format!(
        "# Generated by rustrun for {}\n# Do not edit: it is regenerated on every run.\n\n",
        script.replace(['\n', '\r'], " ")
    ));
    out.push_str("[package]\n");
    out.push_str(&format!("name = {}\n", quote(input.package_name)));
    out.push_str("version = \"0.0.0\"\n");
    out.push_str(&format!("edition = {}\n", quote(input.edition)));
    out.push_str("publish = false\n");
    out.push_str("autobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n\n");

    out.push_str("[[bin]]\n");
    out.push_str(&format!("name = {}\n", quote(input.bin_name)));
    out.push_str(&format!("path = {}\n\n", quote(script)));

    out.push_str("[dependencies]\n");
    for dep in input.deps {
        if dep.features.is_empty() {
            out.push_str(&format!("{} = {}\n", key(&dep.name), quote(&dep.req)));
        } else {
            let features: Vec<String> = dep.features.iter().map(|f| quote(f)).collect();
            out.push_str(&format!(
                "{} = {{ version = {}, features = [{}] }}\n",
                key(&dep.name),
                quote(&dep.req),
                features.join(", ")
            ));
        }
    }

    // An empty workspace table makes this package its own workspace root, so
    // a Cargo.toml in some ancestor of the cache directory can never adopt it.
    out.push_str("\n[workspace]\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn dep(name: &str, req: &str, features: &[&str]) -> ResolvedDep {
        ResolvedDep {
            name: name.into(),
            req: req.into(),
            features: features.iter().map(|s| s.to_string()).collect(),
        }
    }

    fn render_with(path: &str, deps: &[ResolvedDep]) -> toml::Table {
        let path = PathBuf::from(path);
        let text = render(&ManifestInput {
            package_name: "my_script",
            bin_name: "my_script",
            script_path: &path,
            edition: "2021",
            deps,
        })
        .unwrap();
        toml::from_str(&text).unwrap_or_else(|e| panic!("invalid TOML ({e}):\n{text}"))
    }

    #[test]
    fn bin_points_at_original_script() {
        let m = render_with("/home/me/scripts/my script.rs", &[]);
        let bin = &m["bin"].as_array().unwrap()[0];
        assert_eq!(bin["path"].as_str(), Some("/home/me/scripts/my script.rs"));
        assert_eq!(bin["name"].as_str(), Some("my_script"));
        assert_eq!(m["package"]["autobins"].as_bool(), Some(false));
        assert!(m["workspace"].as_table().unwrap().is_empty());
    }

    #[test]
    fn awkward_paths_are_escaped() {
        for p in [r#"/tmp/quote"d/s.rs"#, r"C:\Users\me\script.rs", "/tmp/ünïcødé/✓.rs", "/tmp/new\nline.rs"]
        {
            let m = render_with(p, &[]);
            assert_eq!(m["bin"][0]["path"].as_str(), Some(p));
        }
    }

    #[test]
    fn dependencies_with_and_without_features() {
        let m = render_with(
            "/s.rs",
            &[
                dep("rand", "0.8.5", &[]),
                dep("serde", "1.0.200", &["derive", "rc"]),
                dep("proc-macro2", "1", &[]),
            ],
        );
        let deps = m["dependencies"].as_table().unwrap();
        assert_eq!(deps["rand"].as_str(), Some("0.8.5"));
        assert_eq!(deps["proc-macro2"].as_str(), Some("1"));
        assert_eq!(deps["serde"]["version"].as_str(), Some("1.0.200"));
        let f: Vec<_> =
            deps["serde"]["features"].as_array().unwrap().iter().map(|v| v.as_str().unwrap()).collect();
        assert_eq!(f, ["derive", "rc"]);
    }

    #[test]
    fn key_quoting() {
        assert_eq!(key("serde_json"), "serde_json");
        assert_eq!(key("a.b"), "\"a.b\"");
    }
}
